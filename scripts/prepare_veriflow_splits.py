#!/usr/bin/env python3
"""
VeriFlow Phase V1: Prepare Visible and Hidden Test Splits with Dual Hashes and Canary Tokens.

Splitting Rules:
- HumanEval+ and MBPP+:
    visible = base_input
    hidden  = plus_input
- APPS+:
    visible = example pairs from statement (if none, the first 3 test cases)
    hidden  = all other test cases
    Skip problems with 0 visible tests and count them.

Canary Token:
    Every hidden test suite includes a unique token:
    # CANARY_TOKEN_VERIFLOW_SECRET_<problem_id>_<uuid>
    The repair loop must NEVER expose this canary in any prompt or log when feedback_scope=visible.

Output:
    data/veriflow_splits.json
    Manifest and hash registry
"""

import ast
import base64
from copy import deepcopy
import hashlib
import json
import marshal
from pathlib import Path
import re
import sys
import uuid
import zlib

COMPARE_TEMPLATE = '''# Generated by VeriFlow benchmark splitter
import base64
import marshal
import zlib
import hashlib
import math
import numpy as np
from solution import {entry} as candidate

inf, nan = math.inf, math.nan
{canary_header}

def test_{entry}():
    cases = marshal.loads(zlib.decompress(base64.b85decode({cases})))
    for args, expected, hashed in cases:
        out = candidate(*args)
        if hashed:
            assert isinstance(out, str) and hashlib.sha256(out.encode()).digest() == expected
            continue
        {comparison}
'''

APPS_FUNCTION_TEMPLATE = '''# Generated by VeriFlow benchmark splitter
from solution import {entry}
{canary_header}

def test_{entry}():
    for args, expected in {cases!r}:
        assert {entry}(*args) == expected
'''

APPS_STDIO_TEMPLATE = '''# Generated by VeriFlow benchmark splitter
import subprocess
import sys
{canary_header}

def test_stdio():
    for stdin, expected in {cases!r}:
        run = subprocess.run([sys.executable, '-B', 'solution.py'], input=stdin, text=True, capture_output=True)
        if run.returncode == 0 and not run.stdout and expected.strip():
            run = subprocess.run([sys.executable, '-B', '-c', {driver!r}], input=stdin, text=True, capture_output=True)
        assert run.returncode == 0, run.stderr
        assert run.stdout.strip() == expected.strip()
'''

MBPP_OUTPUT_SET_EQ_TASKS = {
    "similar_elements", "differ_At_One_Bit_Pos", "find_tuples", "get_pairs_count",
    "remove_duplicate", "count_variable_length", "find_even_numbers", "find_odd_numbers",
    "common_in_nested_lists", "find_combinations", "unique_sublists"
}

MBPP_OUTPUT_NOT_NONE_TASKS = {
    "is_sublist", "has_duplicate", "is_woodall", "check_element", "is_prime",
    "check_isosceles", "is_undulating", "is_valid_parentheses"
}


def _surface_Area(b, s):
    return 2 * b * s + b * b


def _digit_distance_nums(n1, n2):
    s1, s2 = str(n1), str(n2)
    m = max(len(s1), len(s2))
    s1, s2 = s1.zfill(m), s2.zfill(m)
    return sum(abs(int(c1) - int(c2)) for c1, c2 in zip(s1, s2))


def normalize_code(code: str) -> str:
    return "\n".join(line.rstrip() for line in code.replace("\r\n", "\n").replace("\r", "\n").split("\n")).strip() + "\n"


def sha256_hash(text: str) -> str:
    return hashlib.sha256(normalize_code(text).encode("utf-8")).hexdigest()


def literal(value):
    if isinstance(value, str):
        try:
            return ast.literal_eval(value)
        except (SyntaxError, ValueError):
            pass
    return value


def deserialize_mbpp_inputs(task_id: str, inputs: list) -> list:
    if task_id in ["Mbpp/106", "Mbpp/720"]:
        res = []
        for inp in inputs:
            if task_id == "Mbpp/106":
                res.append([inp[0], tuple(inp[1])])
            else:
                res.append([tuple(inp[0]), inp[1]])
        return res
    if task_id == "Mbpp/124":
        return [[complex(inp[0]), complex(inp[1])] for inp in inputs]
    if task_id == "Mbpp/252":
        return [[complex(inp[0]) if isinstance(inp[0], str) else inp[0]] for inp in inputs]
    if task_id == "Mbpp/580":
        def to_tup(x):
            return tuple(to_tup(i) if isinstance(i, list) else i for i in x) if isinstance(x, list) else x
        return [[to_tup(inp[0])] for inp in inputs]
    return inputs


def evaluate_plus_cases(row, dataset, all_inputs):
    entry = row['entry_point']
    code = row['canonical_solution']
    processed_inputs = all_inputs
    if dataset == 'mbpp_plus':
        processed_inputs = deserialize_mbpp_inputs(row['task_id'], all_inputs)
    else:
        code = row['prompt'] + code

    scope = {}
    exec(code, scope)
    cases = []
    comparison = 'assert out == expected'

    for args in processed_inputs:
        expected = scope[entry](*deepcopy(args))
        if dataset == 'mbpp_plus' and entry in MBPP_OUTPUT_NOT_NONE_TASKS:
            expected = expected is not None
            comparison = 'assert (out if isinstance(out, bool) else out is not None) == expected'
        elif dataset == 'mbpp_plus' and entry in MBPP_OUTPUT_SET_EQ_TASKS:
            comparison = 'assert set(out) == set(expected)'
        elif dataset == 'humaneval_plus' and entry == 'find_zero':
            comparison = f'assert abs(sum(c * out**i for i, c in enumerate(args[0]))) <= {row.get("atol", 1e-4)!r}'
        elif dataset == 'mbpp_plus' and entry == 'are_equivalent':
            comparison = 'pass  # Official oracle accepts any non-raising return.'
        elif dataset == 'mbpp_plus' and entry == 'sum_div':
            comparison = 'assert out == expected or out == 0'
        elif dataset == 'mbpp_plus' and entry in ('surface_Area', 'digit_distance_nums'):
            alt = (_surface_Area if entry == 'surface_Area' else _digit_distance_nums)(*args)
            expected = (expected, alt)
            comparison = 'assert out in expected'
        else:
            atol_val = row.get("atol", 0)
            comparison = (
                'if out != expected:\n'
                f'            tol = {atol_val!r} or (1e-6 if isinstance(expected, float) or (isinstance(expected, (list, tuple)) and expected and all(isinstance(x, float) for x in expected)) else 0)\n'
                '            assert tol and type(out) is type(expected) and np.shape(out) == np.shape(expected) and np.allclose(out, expected, rtol=1e-7, atol=tol)'
            )

        if isinstance(expected, dict):
            expected = dict(expected)
        hashed = isinstance(expected, str) and len(expected) > 4096
        cases.append((args, hashlib.sha256(expected.encode()).digest() if hashed else expected, hashed))

    return cases, comparison


def render_cases_suite(entry, cases, comparison, canary_token=None):
    if not cases:
        canary_h = f"# {canary_token}\n" if canary_token else ""
        return f"{canary_h}# Empty test suite\ndef test_noop():\n    pass\n"

    canary_header = f"# {canary_token}" if canary_token else ""
    return COMPARE_TEMPLATE.format(
        entry=entry,
        canary_header=canary_header,
        cases=repr(base64.b85encode(zlib.compress(marshal.dumps(cases)))),
        comparison=comparison
    )


def extract_apps_splits(row, canary_token):
    inputs = row.get('inputs', [])
    outputs = row.get('outputs', [])
    prompt = row.get('prompt', '')
    total = min(len(inputs), len(outputs))

    if total == 0:
        return None  # 0 visible tests -> skip

    # Find statement example matches
    matched_indices = []
    for idx in range(total):
        inp_str = str(inputs[idx]).strip() if not isinstance(inputs[idx], list) else str(inputs[idx])
        if inp_str and inp_str in prompt:
            matched_indices.append(idx)

    if matched_indices:
        visible_indices = matched_indices
    else:
        # Fallback to first 3 test cases
        visible_indices = list(range(min(3, total)))

    hidden_indices = [i for i in range(total) if i not in visible_indices]

    vis_in = [inputs[i] for i in visible_indices]
    vis_out = [outputs[i] for i in visible_indices]

    hid_in = [inputs[i] for i in hidden_indices]
    hid_out = [outputs[i] for i in hidden_indices]

    starter = row.get('starter_code', '')
    entry_match = re.search(r'\bdef (\w+)\s*\(', starter)
    entry = entry_match.group(1) if entry_match else "main"

    is_func = bool(inputs and isinstance(inputs[0], list) and entry_match)

    def render(in_list, out_list, canary):
        if not in_list:
            canary_h = f"# {canary}\n" if canary else ""
            return f"{canary_h}# Empty suite\ndef test_noop():\n    pass\n"
        if is_func:
            cases = [([literal(arg) for arg in args], literal(expected[0])) for args, expected in zip(in_list, out_list, strict=True)]
            canary_h = f"# {canary}" if canary else ""
            return APPS_FUNCTION_TEMPLATE.format(entry=entry, canary_header=canary_h, cases=cases)
        else:
            cases = list(zip(in_list, out_list))
            driver = f"import solution; fn = getattr(solution, '{entry}', None) or getattr(solution, 'main'); fn()"
            canary_h = f"# {canary}" if canary else ""
            return APPS_STDIO_TEMPLATE.format(canary_header=canary_h, cases=cases, driver=driver)

    vis_code = render(vis_in, vis_out, None)
    hid_code = render(hid_in, hid_out, canary_token)
    full_code = render(inputs, outputs, canary_token)

    return {
        'visible_cases_count': len(vis_in),
        'hidden_cases_count': len(hid_in),
        'visible_code': vis_code,
        'hidden_code': hid_code,
        'full_code': full_code,
    }


def main():
    print("=" * 65, flush=True)
    print(" VeriFlow Phase V1: Preparing Benchmark Splits & Two Hashes ", flush=True)
    print("=" * 65, flush=True)

    data_dir = Path("data")
    splits = {}
    skipped_count = 0

    # 1. HumanEval+ (164 tasks)
    print("Processing HumanEval+...", flush=True)
    he_path = data_dir / "humaneval_plus.jsonl"
    with open(he_path, "r", encoding="utf-8") as f:
        for idx, line in enumerate(f):
            if not line.strip(): continue
            row = json.loads(line)
            pid = row["task_id"]
            canary = f"CANARY_TOKEN_VERIFLOW_SECRET_{pid.replace('/', '_')}_{uuid.uuid4().hex[:12]}"
            
            base_in = row.get("base_input", [])
            plus_in = row.get("plus_input", [])
            all_in = base_in + plus_in

            cases, comparison = evaluate_plus_cases(row, "humaneval_plus", all_in)
            cases_vis = cases[:len(base_in)]
            cases_hid = cases[len(base_in):]

            vis_code = render_cases_suite(row["entry_point"], cases_vis, comparison)
            hid_code = render_cases_suite(row["entry_point"], cases_hid, comparison, canary_token=canary)
            full_code = render_cases_suite(row["entry_point"], cases, comparison, canary_token=canary)

            v_hash = sha256_hash(vis_code)
            h_hash = sha256_hash(hid_code)
            f_hash = sha256_hash(full_code)

            splits[pid] = {
                "benchmark": "humaneval_plus",
                "problem_id": pid,
                "entry_point": row["entry_point"],
                "prompt": row["prompt"],
                "canary_token": canary,
                "visible_cases_count": len(base_in),
                "hidden_cases_count": len(plus_in),
                "visible_hash": v_hash,
                "hidden_hash": h_hash,
                "full_hash": f_hash,
                "visible_code": vis_code,
                "hidden_code": hid_code,
                "full_code": full_code
            }

    print(f"  [OK] HumanEval+: {len([p for p in splits.values() if p['benchmark'] == 'humaneval_plus'])} tasks processed.", flush=True)

    # 2. MBPP+ (399 tasks)
    print("Processing MBPP+...", flush=True)
    mbpp_path = data_dir / "mbpp_plus.jsonl"
    with open(mbpp_path, "r", encoding="utf-8") as f:
        for idx, line in enumerate(f):
            if not line.strip(): continue
            row = json.loads(line)
            pid = row["task_id"]
            canary = f"CANARY_TOKEN_VERIFLOW_SECRET_{pid.replace('/', '_')}_{uuid.uuid4().hex[:12]}"
            
            base_in = row.get("base_input", [])
            plus_in = row.get("plus_input", [])
            if pid == "Mbpp/793" and plus_in == {}:
                plus_in = []
            all_in = base_in + plus_in

            cases, comparison = evaluate_plus_cases(row, "mbpp_plus", all_in)
            cases_vis = cases[:len(base_in)]
            cases_hid = cases[len(base_in):]

            vis_code = render_cases_suite(row["entry_point"], cases_vis, comparison)
            hid_code = render_cases_suite(row["entry_point"], cases_hid, comparison, canary_token=canary)
            full_code = render_cases_suite(row["entry_point"], cases, comparison, canary_token=canary)

            v_hash = sha256_hash(vis_code)
            h_hash = sha256_hash(hid_code)
            f_hash = sha256_hash(full_code)

            splits[pid] = {
                "benchmark": "mbpp_plus",
                "problem_id": pid,
                "entry_point": row["entry_point"],
                "prompt": row["prompt"],
                "canary_token": canary,
                "visible_cases_count": len(base_in),
                "hidden_cases_count": len(plus_in),
                "visible_hash": v_hash,
                "hidden_hash": h_hash,
                "full_hash": f_hash,
                "visible_code": vis_code,
                "hidden_code": hid_code,
                "full_code": full_code
            }

    print(f"  [OK] MBPP+: {len([p for p in splits.values() if p['benchmark'] == 'mbpp_plus'])} tasks processed.", flush=True)

    # 3. APPS+ (600 tasks)
    print("Processing APPS+...", flush=True)
    apps_path = data_dir / "apps_plus_selected.jsonl"
    with open(apps_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip(): continue
            row = json.loads(line)
            pid = row.get("problem_id", "")
            canary = f"CANARY_TOKEN_VERIFLOW_SECRET_{pid}_{uuid.uuid4().hex[:12]}"

            res = extract_apps_splits(row, canary)
            if res is None:
                skipped_count += 1
                continue

            v_hash = sha256_hash(res["visible_code"])
            h_hash = sha256_hash(res["hidden_code"])
            f_hash = sha256_hash(res["full_code"])

            splits[pid] = {
                "benchmark": "apps_plus",
                "difficulty": row.get("difficulty", "unknown"),
                "problem_id": pid,
                "entry_point": row.get("starter_code", ""),
                "prompt": row["prompt"],
                "canary_token": canary,
                "visible_cases_count": res["visible_cases_count"],
                "hidden_cases_count": res["hidden_cases_count"],
                "visible_hash": v_hash,
                "hidden_hash": h_hash,
                "full_hash": f_hash,
                "visible_code": res["visible_code"],
                "hidden_code": res["hidden_code"],
                "full_code": res["full_code"]
            }

    print(f"  [OK] APPS+: {len([p for p in splits.values() if p['benchmark'] == 'apps_plus'])} tasks processed.", flush=True)
    print(f"  [INFO] Problems skipped due to 0 visible tests: {skipped_count}", flush=True)

    total_problems = len(splits)
    print(f"\nTOTAL SPLIT PROBLEMS: {total_problems}", flush=True)

    out_file = data_dir / "veriflow_splits.json"
    print(f"Writing splits to {out_file}...", flush=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(splits, f, indent=2)

    splits_digest = sha256_hash(json.dumps(splits, sort_keys=True))
    print(f"[SUCCESS] Splits written. SHA-256 Digest: {splits_digest}", flush=True)
    return splits_digest


if __name__ == "__main__":
    main()

import React, { useCallback, useRef, useState } from 'react';
import { ArrowRight } from 'lucide-react';
import type { ApiErrorView } from '../../api/client';
import type { ApiSettings, GeneratedCodeFile } from '../../api/types';
import { processPromptWithAgents } from '../../services/aiService';
import type { GenerateResult, StageStatus } from '../../state/workbench';
import { useWorkbench } from '../../state/WorkbenchContext';
import { ErrorState, LoadingState } from '../common/AsyncState';
import { Step1Input } from '../Step1Input';
import { CodeFileViewer } from '../Step2CodeOutput';
import { runStageOperation } from './stageModel';

/** Operation name shown in Generate error states. */
export const GENERATE_OPERATION = 'code generation';

/** Produces files for a prompt (real LLM output); must reject on failure. */
export type Generator = (prompt: string) => Promise<GenerateResult>;

export const NO_FILES_MESSAGE =
  'The model returned no Python files. Describe a Python project or program to generate.';

/** Generator backed by the configured LLM provider (`services/aiService`). */
export function createProviderGenerator(apiSettings: ApiSettings, temperature = 0.1): Generator {
  return async (prompt) => {
    const data = await processPromptWithAgents(prompt, apiSettings, undefined, temperature);
    if (data.generatedCode.length === 0) throw new Error(NO_FILES_MESSAGE);
    return { prompt, files: data.generatedCode, modelUsed: data.modelUsed || undefined };
  };
}

export interface GenerateStageViewProps {
  status: StageStatus;
  error?: ApiErrorView;
  prompt: string;
  onPromptChange: (prompt: string) => void;
  onGenerate: () => void;
  /** Resends the failed request with the prompt it used (23.3). */
  onRetry: () => void;
  /** Working files; shown once generation has completed. */
  files: GeneratedCodeFile[];
  modelUsed?: string;
  onContinue: () => void;
}

/** Presentational Generate stage: prompt composer, loading/error state, and the file viewer. */
export const GenerateStageView: React.FC<GenerateStageViewProps> = ({
  status,
  error,
  prompt,
  onPromptChange,
  onGenerate,
  onRetry,
  files,
  modelUsed,
  onContinue,
}) => {
  const running = status === 'running';
  const showFiles = status === 'complete' && files.length > 0;
  return (
    <div className="flex flex-col" aria-busy={running || undefined}>
      <Step1Input prompt={prompt} onPromptChange={onPromptChange} onProcess={onGenerate} isProcessing={running} />

      <div className="max-w-6xl w-full mx-auto px-4 md:px-6 pb-8 flex flex-col gap-4">
        {running ? <LoadingState label="Generating code" /> : null}
        {status === 'failed' && error ? <ErrorState error={error} onRetry={onRetry} /> : null}

        {showFiles ? (
          <section aria-labelledby="generate-files-title" className="flex flex-col gap-4">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <div>
                <h2 id="generate-files-title" className="text-lg font-bold text-[color:var(--color-ink)]">
                  Working files
                </h2>
                <p className="text-sm text-[color:var(--color-ink-muted)]">
                  {files.length} {files.length === 1 ? 'file' : 'files'}
                  {modelUsed ? ` · generated by ${modelUsed}` : ''}
                </p>
              </div>
              <button
                type="button"
                onClick={onContinue}
                className="btn-primary px-5 py-2.5 text-sm flex items-center gap-2"
              >
                <span>Continue to Verify</span>
                <ArrowRight aria-hidden="true" className="w-4 h-4" />
              </button>
            </div>
            <CodeFileViewer files={files} />
          </section>
        ) : null}
      </div>
    </div>
  );
};

export interface GenerateStageProps {
  generate: Generator;
}

/** Generate stage wired to the Workbench reducer. */
export const GenerateStage: React.FC<GenerateStageProps> = ({ generate }) => {
  const { state, dispatch } = useWorkbench();
  const [draft, setDraft] = useState(state.prompt);
  /** Prompt of the last request, resent unchanged by Retry (23.3). */
  const lastPrompt = useRef(state.prompt);
  const stage = state.stages.generate;

  const run = useCallback(
    (prompt: string) => {
      if (!prompt.trim() || stage.status === 'running') return;
      lastPrompt.current = prompt;
      void runStageOperation(dispatch, 'generate', GENERATE_OPERATION, () => generate(prompt));
    },
    [dispatch, generate, stage.status],
  );

  return (
    <GenerateStageView
      status={stage.status}
      error={stage.error}
      prompt={draft}
      onPromptChange={setDraft}
      onGenerate={() => run(draft)}
      onRetry={() => run(lastPrompt.current)}
      files={state.files}
      modelUsed={state.results.generate?.modelUsed}
      onContinue={() => dispatch({ type: 'SELECT', stage: 'verify' })}
    />
  );
};

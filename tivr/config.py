"""Run configuration for ``python -m tivr.run_benchmark`` (design §3 Configuration).

All validation happens in :func:`parse_config` before any client, directory, or
network activity. Every failure prints ``error: --<flag>: <reason>`` to stderr and
exits with status 2 (Requirements 2.8, 11.13, 12.1, 12.2, 13.5).

:class:`Decoding` is shared with ``tivr.llm_client`` so generation and repair use
one decoding configuration per run (Requirement 11.11).
"""
from __future__ import annotations

import argparse
import math
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, NoReturn, Sequence

# ---------------------------------------------------------------------------
# Accepted values and defaults
# ---------------------------------------------------------------------------

CORE_MODES: tuple[str, ...] = (
    "dou", "dou_no_bt", "generic", "evidence_only", "taxonomy_only", "full",
)
OPTIONAL_MODES: tuple[str, ...] = ("intervenor", "dou_intervenor")
ALL_MODES: tuple[str, ...] = CORE_MODES + OPTIONAL_MODES

FEEDBACK_REGIMES: tuple[str, ...] = ("dou", "strict")
PROMPT_STYLES: tuple[str, ...] = ("dou", "tivr")

DEFAULT_MODE = "dou"
DEFAULT_REGIME = "dou"
DEFAULT_K = 2
DEFAULT_TEMPERATURE = 0.1
DEFAULT_PROMPT_STYLE = "dou"
DEFAULT_SAMPLE_SIZE = 120
DEFAULT_SEED = 0
DEFAULT_LLM_RETRIES = 2
MAX_LLM_RETRIES = 10
DEFAULT_MODEL = "deepseek-chat"
DEFAULT_RUNS_ROOT = "runs"

RUN_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$")

CONFIG_EXIT_CODE = 2


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Decoding:
    """Decoding parameters sent with every generation and repair request.

    ``top_p`` and ``max_tokens`` are ``None`` when not supplied and are then
    omitted from request payloads (Requirements 2.1-2.5).
    """
    temperature: float = DEFAULT_TEMPERATURE
    top_p: float | None = None
    max_tokens: int | None = None

    def as_dict(self) -> dict[str, Any]:
        """Manifest/summary/cache representation (nulls for unsent values)."""
        return {"temperature": self.temperature, "top_p": self.top_p, "max_tokens": self.max_tokens}


@dataclass(frozen=True)
class RunConfig:
    dataset: Path
    mode: str = DEFAULT_MODE
    enable_intervenor: bool = False
    feedback_regime: str = DEFAULT_REGIME
    k: int = DEFAULT_K
    decoding: Decoding = Decoding()
    generation_prompt_style: str = DEFAULT_PROMPT_STYLE
    sample_size: int = DEFAULT_SAMPLE_SIZE
    seed: int = DEFAULT_SEED
    generation_cache: Path | None = None
    mock: bool = False
    llm_retries: int = DEFAULT_LLM_RETRIES
    model: str = DEFAULT_MODEL
    run_id: str | None = None          # None → generated by rundir
    runs_root: Path = Path(DEFAULT_RUNS_ROOT)

    @property
    def llm_mode(self) -> str:
        return "mock" if self.mock else "live"


class ConfigError(Exception):
    """A single invalid setting. ``str(err)`` is ``--<flag>: <reason>``."""

    def __init__(self, flag: str, reason: str) -> None:
        self.flag = flag
        self.reason = reason
        super().__init__(f"{flag}: {reason}" if flag else reason)


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------

class _Parser(argparse.ArgumentParser):
    """argparse errors (unknown flags, missing DATASET) also exit 2 with ``error: ...``."""

    def error(self, message: str) -> NoReturn:
        # argparse messages already name the argument, e.g. "argument --k: expected one argument".
        raise ConfigError("", message)


def _build_parser() -> argparse.ArgumentParser:
    # Every value is taken as a string so validation and messages stay uniform.
    p = _Parser(prog="python -m tivr.run_benchmark", allow_abbrev=False,
                description="TIVR paper-aligned repair benchmark runner")
    p.add_argument("dataset", metavar="DATASET", help="Task_Record JSONL dataset")
    p.add_argument("--mode", default=DEFAULT_MODE, help=f"repair mode: {', '.join(ALL_MODES)}")
    p.add_argument("--enable-intervenor", action="store_true",
                   help="allow the optional intervenor and dou_intervenor modes")
    p.add_argument("--feedback-regime", default=DEFAULT_REGIME, help="dou or strict")
    p.add_argument("--k", default=str(DEFAULT_K), help="repair iteration budget (>= 1)")
    p.add_argument("--temperature", default=str(DEFAULT_TEMPERATURE), help="0.0 to 2.0")
    p.add_argument("--top-p", default=None, help="greater than 0.0, at most 1.0")
    p.add_argument("--max-tokens", default=None, help="integer >= 1")
    p.add_argument("--generation-prompt-style", default=DEFAULT_PROMPT_STYLE, help="dou or tivr")
    p.add_argument("--sample-size", default=str(DEFAULT_SAMPLE_SIZE), help="repair sample size N (>= 1)")
    p.add_argument("--seed", default=str(DEFAULT_SEED), help="sampling seed S (>= 0)")
    p.add_argument("--generation-cache", default=None, help="reuse a Generation_Cache file")
    p.add_argument("--mock", action="store_true", help="use the offline mock LLM client")
    p.add_argument("--llm-retries", default=str(DEFAULT_LLM_RETRIES), help="0 to 10")
    p.add_argument("--model", default=None, help="model name (default $TIVR_MODEL or deepseek-chat)")
    p.add_argument("--run-id", default=None, help="explicit run ID")
    p.add_argument("--runs-root", default=DEFAULT_RUNS_ROOT, help="directory holding run directories")
    return p


def _parse_int(flag: str, raw: str, *, minimum: int, maximum: int | None = None) -> int:
    rng = f"an integer >= {minimum}" if maximum is None else f"an integer from {minimum} to {maximum}"
    try:
        value = int(raw.strip(), 10)
    except (ValueError, AttributeError):
        raise ConfigError(flag, f"must be {rng} (got {raw!r})") from None
    if value < minimum or (maximum is not None and value > maximum):
        raise ConfigError(flag, f"must be {rng} (got {raw!r})")
    return value


def _parse_float(flag: str, raw: str, rng: str) -> float:
    try:
        value = float(raw.strip())
    except (ValueError, AttributeError):
        raise ConfigError(flag, f"must be a number {rng} (got {raw!r})") from None
    if not math.isfinite(value):
        raise ConfigError(flag, f"must be a number {rng} (got {raw!r})")
    return value


def _choice(flag: str, raw: str, accepted: Sequence[str]) -> str:
    if raw not in accepted:
        raise ConfigError(flag, f"must be one of {', '.join(accepted)} (got {raw!r})")
    return raw


def build_config(argv: Sequence[str], env: Mapping[str, str] | None = None) -> RunConfig:
    """Parse and validate ``argv``; raise :class:`ConfigError` on the first invalid setting."""
    env = os.environ if env is None else env
    ns = _build_parser().parse_args(list(argv))

    # Mode and the optional-mode gate (11.13).
    mode = _choice("--mode", ns.mode, ALL_MODES)
    if mode in OPTIONAL_MODES and not ns.enable_intervenor:
        raise ConfigError("--mode", f"mode {mode!r} is optional and requires --enable-intervenor")

    regime = _choice("--feedback-regime", ns.feedback_regime, FEEDBACK_REGIMES)  # 12.1, 12.2
    k = _parse_int("--k", ns.k, minimum=1)

    # Decoding (2.8).
    temperature = _parse_float("--temperature", ns.temperature, "from 0.0 to 2.0 inclusive")
    if not 0.0 <= temperature <= 2.0:
        raise ConfigError("--temperature", f"must be a number from 0.0 to 2.0 inclusive (got {ns.temperature!r})")
    top_p: float | None = None
    if ns.top_p is not None:
        top_p = _parse_float("--top-p", ns.top_p, "greater than 0.0 and at most 1.0")
        if not 0.0 < top_p <= 1.0:
            raise ConfigError("--top-p", f"must be a number greater than 0.0 and at most 1.0 (got {ns.top_p!r})")
    max_tokens: int | None = None
    if ns.max_tokens is not None:
        max_tokens = _parse_int("--max-tokens", ns.max_tokens, minimum=1)
    style = _choice("--generation-prompt-style", ns.generation_prompt_style, PROMPT_STYLES)

    # Sampling (13.5).
    sample_size = _parse_int("--sample-size", ns.sample_size, minimum=1)
    seed = _parse_int("--seed", ns.seed, minimum=0)

    # LLM client settings (1.6).
    retries = _parse_int("--llm-retries", ns.llm_retries, minimum=0, maximum=MAX_LLM_RETRIES)
    if ns.model is not None:
        model = ns.model.strip()
        if not model:
            raise ConfigError("--model", "must be a non-empty model name")
    else:
        model = (env.get("TIVR_MODEL") or "").strip() or DEFAULT_MODEL

    # Paths and run identity.
    if not ns.dataset.strip():
        raise ConfigError("DATASET", "must be a non-empty path")
    cache: Path | None = None
    if ns.generation_cache is not None:
        if not ns.generation_cache.strip():
            raise ConfigError("--generation-cache", "must be a non-empty path")
        cache = Path(ns.generation_cache)
    if ns.run_id is not None and not RUN_ID_PATTERN.fullmatch(ns.run_id):
        raise ConfigError(
            "--run-id",
            "must start with a letter or digit and contain only letters, digits, '_', '.', '-' "
            f"(1-100 characters) (got {ns.run_id!r})",
        )
    if not ns.runs_root.strip():
        raise ConfigError("--runs-root", "must be a non-empty path")

    return RunConfig(
        dataset=Path(ns.dataset),
        mode=mode,
        enable_intervenor=bool(ns.enable_intervenor),
        feedback_regime=regime,
        k=k,
        decoding=Decoding(temperature=temperature, top_p=top_p, max_tokens=max_tokens),
        generation_prompt_style=style,
        sample_size=sample_size,
        seed=seed,
        generation_cache=cache,
        mock=bool(ns.mock),
        llm_retries=retries,
        model=model,
        run_id=ns.run_id,
        runs_root=Path(ns.runs_root),
    )


def parse_config(argv: Sequence[str] | None = None, env: Mapping[str, str] | None = None) -> RunConfig:
    """CLI entry: validate ``argv`` (default ``sys.argv[1:]``) or exit 2 with ``error: --<flag>: <reason>``."""
    try:
        return build_config(sys.argv[1:] if argv is None else argv, env)
    except ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(CONFIG_EXIT_CODE) from None
